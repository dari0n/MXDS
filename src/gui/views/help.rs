//! Экран «Помощь»: краткая инструкция по использованию MXDS.

use crate::gui::app::MxdsApp;

/// Текст инструкции (единый источник — легко править).
const HELP_TEXT: &str = r#"БЫСТРЫЙ СТАРТ

1. Запустите MXDS от имени администратора — без этого движок
   и авто-исправления недоступны.
2. На экране «Профили» выберите профиль (рекомендуемый — general)
   или доверьтесь автоподбору (см. ниже).
3. На экране «Движок» или «Главная» нажмите «Запустить».
4. Проверьте доступность сервисов на экране «Доступность».

АВТОПОДБОР ПРОФИЛЯ

По умолчанию при запуске движка MXDS сам проверяет профили:
сначала активный, затем остальные (приоритет — ранее отмеченным
рабочими). Для каждого кандидата выполняется проверка YouTube
каскадом DNS → TCP → TLS → HTTP; первый рабочий профиль становится
активным, результаты запоминаются (значки совместимости на экране
«Профили»). Перебор занимает до нескольких минут — прогресс виден
в баннере сверху. Отключается на экране «Конфигурация»
(«Автоподбор профиля»).

ПРОФИЛИ

Профиль — это набор стратегий обхода (Discord, YouTube и др.).
Профили хранятся в папке profiles\ рядом с программой, формат —
обычные .bat-файлы (совместимы с zapret-discord-youtube).

Создание профиля:
  • В GUI: экран «Профили» → форма «Создать профиль» — задайте
    идентификатор (латиница), имя и, при желании, профиль-источник
    для копирования.
  • В CLI: mxds profiles create <id> [--from <профиль>]
           [--name <имя>] [--description <описание>]
  • Вручную: скопируйте готовый .bat в profiles\ и обновите список
    кнопкой «Обновить».

Подробное руководство — в файле docs\PROFILE_GUIDE.md в папке
установки.

ДИАГНОСТИКА И АВТО-ИСПРАВЛЕНИЯ

Экран «Диагностика» проверяет систему: права, службы BFE и
WinDivert, TCP timestamps, Secure DNS, конфликтующие службы
(GoodbyeDPI, zapret, Adguard и др.).

У проверок со статусом [!] или [X], которые можно исправить
автоматически, показывается кнопка «Исправить». Кнопка
«Исправить все» выполняет все доступные исправления сразу.
Исправления меняют настройки ОС и требуют прав администратора.

CLI-КОМАНДЫ

  mxds run [--profile <id>]  — запустить движок (от администратора);
                               без --profile профиль подбирается
                               автоматически (см. автоподбор выше)
  mxds stop                  — остановить движок
  mxds status                — состояние движка и активный профиль
  mxds diagnostics           — прогон диагностики в терминале
  mxds diagnostics --fix     — применить авто-исправления и
                               повторить диагностику
  mxds check                 — проверка доступности целей
  mxds profiles list         — список профилей
  mxds profiles create …     — создать профиль

ТИПОВЫЕ ПРОБЛЕМЫ

• «Другой экземпляр MXDS уже запущен» — закройте вторую копию
  или выполните mxds stop.
• Антивирус блокирует WinDivert — добавьте папку MXDS в
  исключения (бинарники подписаны и проверены по SHA256).
• Обход работает, но сервис не открывается — попробуйте другой
  профиль; проверьте экран «Доступность».
• Путь установки содержит кириллицу или лежит в OneDrive —
  перенесите MXDS, например в C:\mxds.
"#;

pub fn show(ui: &mut egui::Ui, _app: &mut MxdsApp) {
    ui.heading("Помощь");
    ui.add_space(8.0);
    egui::ScrollArea::vertical().show(ui, |ui| {
        for line in HELP_TEXT.lines() {
            if line.is_empty() {
                ui.add_space(6.0);
            } else if line.chars().all(|c| c.is_uppercase() || !c.is_alphabetic()) {
                // Заголовки секций — строки ПОЛНОСТЬЮ В ВЕРХНЕМ РЕГИСТРЕ.
                ui.add_space(4.0);
                ui.strong(line);
            } else {
                ui.label(line);
            }
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn help_text_covers_key_topics() {
        for topic in [
            "БЫСТРЫЙ СТАРТ",
            "ПРОФИЛИ",
            "ДИАГНОСТИКА",
            "CLI",
            "ТИПОВЫЕ ПРОБЛЕМЫ",
        ] {
            assert!(HELP_TEXT.contains(topic), "нет секции {topic}");
        }
        // Без обрывов: каждая строка не пустая-висячая и текст закончен.
        assert!(HELP_TEXT.trim_end().ends_with("C:\\mxds."));
    }
}
